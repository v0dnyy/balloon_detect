"""
Конфигурация PID-контроллеров для задачи удержания шарика в центре кадра.

Оси:
  x  — горизонтальное смещение (право/лево)   → управляет рысканьем (yaw) или боковой скоростью
  y  — вертикальное смещение  (вверх/вниз)    → управляет тягой / вертикальной скоростью
  z  — ошибка расстояния (area_ratio)          → управляет скоростью вперёд/назад

Нормализация ошибок (всегда ∈ [-1.0, +1.0]):
  error_x = (cx_norm - target_cx) / 0.5
  error_y = (cy_norm - target_cy) / 0.5
  error_z = (target_area - current_area) / target_area  → clip(-1, 1)

Выходы PID (скорости в м/с, тягой не управляем напрямую):
  vx — скорость вправо (м/с) в теле дрона  (управляется через x-ошибку)
  vy — скорость вниз   (м/с)               (управляется через y-ошибку, знак инвертирован)
  vz — скорость вперёд (м/с)               (управляется через z-ошибку)
"""

from dataclasses import dataclass


@dataclass
class PIDConfig:
    # ── Целевая позиция в кадре ────────────────────────────────────────────
    # Нормализованный центр: (0.5, 0.5) — центр кадра
    target_cx_norm: float = 0.5
    target_cy_norm: float = 0.5

    # Целевая площадь — доля кадра, которую должен занимать шарик.
    # 0.04 = 4% площади кадра (~примерно дрон в 2-3 м от шарика, зависит от камеры)
    # Подбирается экспериментально!
    target_area_ratio: float = 0.005

    # ── PID по оси X (горизонт) → yaw в градусах/сек ──────────────────────
    pid_x_kp: float = 40.0   # пропорциональный
    pid_x_ki: float = 0.5    # интегральный
    pid_x_kd: float = 3.0    # дифференциальный
    max_yaw_rate_deg: float = 15.0   # ±30 °/с — предел yaw rate

    # ── PID по оси Y (вертикаль) → thrust delta ───────────────────────────
    pid_y_kp: float = 0.4
    pid_y_ki: float = 0.05
    pid_y_kd: float = 0.02
    max_thrust_delta: float = 0.15   # ±0.25 от base_thrust
    base_thrust: float = 0.5         # hover thrust (интерпретируется как climb rate)

    # ── PID по оси Z (дистанция) → pitch в градусах ───────────────────────
    pid_z_kp: float = 15.0
    pid_z_ki: float = 0.2
    pid_z_kd: float = 2.0
    max_pitch_deg: float = 12.5   # ±15° — предел наклона вперёд/назад

    # ── Зоны нечувствительности (deadband) ────────────────────────────────
    # Если ошибка меньше порога — считаем, что объект уже в нужном месте.
    # Это убирает дрожание дрона, когда шарик почти в центре.
    deadband_x: float = 0.03   # 5% от половины ширины кадра
    deadband_y: float = 0.03   # 5% от половины высоты кадра
    deadband_z: float = 0.03   # 3% от целевого area_ratio

    thrust_min: float = 0.35   # не даём дрону упасть
    thrust_max: float = 0.75   # не даём уйти на полный газ
    
    # ── Параметры накопления интегральной составляющей ────────────────────
    # Ограничивает integral windup — накопление I при длительной ошибке.
    integral_limit: float = 0.3

    # ── Поведение при потере объекта ──────────────────────────────────────
    # Сколько кадров ждём, пока объект пропал, перед тем как зависнуть (hover).
    max_lost_frames: int = 15

    # ── MAVLink / управление ──────────────────────────────────────────────
    # Режим, в котором дрон слушает SET_POSITION_TARGET_LOCAL_NED
    guided_mode: str = "GUIDED_NOGPS"
